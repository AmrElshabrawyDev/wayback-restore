/**
 * Turns assets/logo.svg into the pixel grid the terminal banner draws with
 * half-block characters (src/cli/logo-pixels.js).
 *
 * Only needed when the logo changes. Uses Playwright's Chromium to render the SVG:
 *   npx playwright install chromium   (once)
 *   node scripts/logo-to-terminal.mjs [size=26]
 */
import { readFile, writeFile } from "node:fs/promises";
import { chromium } from "playwright";

const size = Number(process.argv[2] || 26);
const svg = await readFile(new URL("../assets/logo.svg", import.meta.url), "utf8");

const browser = await chromium.launch();
const page = await browser.newPage();
// draw 16× larger, then average each 16×16 block into one pixel (smooth edges)
const grid = await page.evaluate(async ({ svg, size }) => {
  const S = 16;
  const big = size * S;
  const img = new Image();
  img.src = `data:image/svg+xml;base64,${btoa(unescape(encodeURIComponent(svg)))}`;
  await img.decode();
  const canvas = document.createElement("canvas");
  canvas.width = canvas.height = big;
  const ctx = canvas.getContext("2d");
  ctx.drawImage(img, 0, 0, big, big);
  const data = ctx.getImageData(0, 0, big, big).data;
  const rows = [];
  for (let y = 0; y < size; y++) {
    const row = [];
    for (let x = 0; x < size; x++) {
      let r = 0, g = 0, b = 0, a = 0;
      for (let j = 0; j < S; j++) {
        for (let i = 0; i < S; i++) {
          const k = ((y * S + j) * big + x * S + i) * 4;
          const alpha = data[k + 3] / 255;
          r += data[k] * alpha;
          g += data[k + 1] * alpha;
          b += data[k + 2] * alpha;
          a += alpha;
        }
      }
      row.push(a ? [r / a, g / a, b / a, a / (S * S)] : [0, 0, 0, 0]);
    }
    rows.push(row);
  }
  return rows;
}, { svg, size });
await browser.close();

// mostly-transparent pixels (the outer glow) are left out; edges are darkened
// towards a dark terminal background instead of being half see-through
const BACKGROUND = 0x11;
const hex = ([r, g, b, a]) =>
  a < 0.3 ? "------" : [r, g, b].map((v) => Math.round(v * a + BACKGROUND * (1 - a)).toString(16).padStart(2, "0")).join("");

const source = `// Generated by scripts/logo-to-terminal.mjs from assets/logo.svg — don't edit by hand.
// One string per pixel row, 6 hex digits per pixel, "------" = transparent.
export const LOGO_PIXELS = [
${grid.map((row) => `  "${row.map(hex).join("")}",`).join("\n")}
];
`;
await writeFile(new URL("../src/cli/logo-pixels.js", import.meta.url), source);
console.log(`src/cli/logo-pixels.js: ${size}×${size} pixels → ${size} columns × ${Math.ceil(size / 2)} rows`);
